"""Build data/geo.js (SVG paths for the Texas map) from US Census TIGERweb GeoJSON.

Usage:
    python -I tools/build_map.py <states.json> <counties.json> <interstates.json> > data/geo.js

The inputs come from the Census TIGERweb REST service (public domain):
  State_County/MapServer/0 (states), /1 (counties, STATE='48'), Transportation/MapServer/0 (interstates),
each queried with outSR=4326, maxAllowableOffset=0.01, f=geojson.
"""
import json
import math
import sys

# Projection: equirectangular, scaled for 31 degrees north. Must match map.js.
K = 60.0
COS = math.cos(math.radians(31))
LON0, LON1 = -107.2, -92.6   # view west / east edge
LAT0, LAT1 = 25.4, 36.9      # view south / north edge
W = round((LON1 - LON0) * K * COS)
H = round((LAT1 - LAT0) * K)


def proj(lon, lat):
    return ((lon - LON0) * K * COS, (LAT1 - lat) * K)


def rdp(pts, eps):
    """Ramer-Douglas-Peucker line simplification."""
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    best, idx = 0.0, 0
    for i in range(1, len(pts) - 1):
        x0, y0 = pts[i]
        d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, idx = d, i
    if best > eps:
        return rdp(pts[: idx + 1], eps)[:-1] + rdp(pts[idx:], eps)
    return [pts[0], pts[-1]]


def ring_path(coords, eps, closed=True, min_pts=3):
    raw = [proj(lon, lat) for lon, lat in coords]
    if closed and len(raw) > 4:
        # A closed ring starts and ends on the same point, so simplify it as two halves.
        mid = len(raw) // 2
        pts = rdp(raw[: mid + 1], eps)[:-1] + rdp(raw[mid:], eps)
    else:
        pts = rdp(raw, eps)
    if len(pts) < min_pts:
        return ""
    s = "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts)
    return s + ("Z" if closed else "")


def geom_path(geom, eps, closed=True):
    t, c = geom["type"], geom["coordinates"]
    if t == "Polygon":
        rings = c
    elif t == "MultiPolygon":
        rings = [r for poly in c for r in poly]
    elif t == "LineString":
        rings = [c]
    elif t == "MultiLineString":
        rings = c
    else:
        return ""
    return "".join(ring_path(r, eps, closed, 3 if closed else 2) for r in rings)


def main():
    states = json.load(open(sys.argv[1], encoding="utf-8"))
    counties = json.load(open(sys.argv[2], encoding="utf-8"))
    roads = json.load(open(sys.argv[3], encoding="utf-8"))

    texas, neighbors = "", []
    for f in states["features"]:
        ab = f["properties"]["STUSAB"]
        d = geom_path(f["geometry"], 0.25)
        if ab == "TX":
            texas = d
        else:
            neighbors.append(d)

    county_d = "".join(geom_path(f["geometry"], 0.5) for f in counties["features"])
    road_d = "".join(geom_path(f["geometry"], 0.6, closed=False) for f in roads["features"])

    # Gulf water. Its inland edge runs inside Texas and Louisiana, which are drawn on top of it;
    # its Mexican edge follows the Tamaulipas coast south of the Rio Grande mouth.
    water = [(-97.146, 25.956), (-97.18, 25.6), (-97.42, 25.2), (-97.53, 24.9), (-97.70, 24.2), (-97.72, 23.5),
             (-97.8, 21.0), (-80.0, 21.0), (-80.0, 30.4), (-94.0, 30.4), (-96.0, 29.6), (-97.0, 28.6),
             (-97.6, 27.6), (-97.65, 26.6), (-97.146, 25.956)]
    water_d = "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in (proj(*p) for p in water)) + "Z"

    labels = [
        {"text": "New Mexico", "at": proj(-105.6, 33.6)},
        {"text": "Oklahoma", "at": proj(-97.4, 35.3)},
        {"text": "Mexico", "at": proj(-102.8, 27.6)},
    ]
    labels = [{"text": l["text"], "x": round(l["at"][0], 1), "y": round(l["at"][1], 1)} for l in labels]

    out = {
        "projection": {"K": K, "lat": 31, "lon0": LON0, "lat1": LAT1},
        "width": W,
        "height": H,
        "texas": texas,
        "neighbors": "".join(neighbors),
        "counties": county_d,
        "roads": road_d,
        "water": water_d,
        "labels": labels,
    }
    sys.stdout.write("// Generated by tools/build_map.py from US Census TIGERweb boundaries (public domain). Do not edit.\n")
    sys.stdout.write("window.TX_GEO = " + json.dumps(out, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    main()
